-- ------------------------------------------------------------------------------------
-- ANALYTICAL QUERIES
-- ------------------------------------------------------------------------------------

-- 1. Customer Lifetime Value (LTV)
-- Calculate total revenue generated by each user
WITH UserSpending AS (
    SELECT s.user_id, SUM(p.price) as total_spent
    FROM sales s
    JOIN product p ON s.product_id = p.product_id
    GROUP BY s.user_id
)
SELECT u.user_id, us.total_spent
FROM users u
JOIN UserSpending us ON u.user_id = us.user_id
ORDER BY us.total_spent DESC;

-- 2. Retention Analysis
-- How many unique days each customer visited the platform?
SELECT user_id, COUNT(DISTINCT order_date) as active_days
FROM sales
GROUP BY user_id
ORDER BY active_days DESC;

-- 3. First Purchase Behavior
-- Identify the first item purchased by each customer to analyze onboarding preferences
WITH RankedSales AS (
    SELECT s.*, RANK() OVER (PARTITION BY user_id ORDER BY order_date ASC) as purchase_rank
    FROM sales s
)
SELECT rs.user_id, p.product_name, rs.order_date
FROM RankedSales rs
JOIN product p ON rs.product_id = p.product_id
WHERE rs.purchase_rank = 1;

-- 4. Membership Impact: First purchase AFTER joining Gold
-- Analyzing behavior change post-loyalty enrollment
WITH PostMembershipSales AS (
    SELECT s.user_id, s.order_date, s.product_id, 
           RANK() OVER (PARTITION BY s.user_id ORDER BY s.order_date ASC) as rnk
    FROM sales s
    JOIN membership_enrollments m ON s.user_id = m.user_id
    WHERE s.order_date >= m.enrollment_date
)
SELECT pms.user_id, p.product_name, pms.order_date
FROM PostMembershipSales pms
JOIN product p ON pms.product_id = p.product_id
WHERE pms.rnk = 1;

-- 5. Pre-Membership Spending
-- Calculate total spend before joining the loyalty program to establish a baseline
WITH PreMembershipSales AS (
    SELECT s.user_id, s.product_id, s.order_date
    FROM sales s
    JOIN membership_enrollments m ON s.user_id = m.user_id
    WHERE s.order_date <= m.enrollment_date
)
SELECT pms.user_id, COUNT(*) as total_orders, SUM(p.price) as total_pre_spend
FROM PreMembershipSales pms
JOIN product p ON pms.product_id = p.product_id
GROUP BY pms.user_id;

-- 6. Loyalty Reward Analysis
-- Calculate reward points earned in the first year of membership (5 pts per 10 units spent)
WITH FirstYearSpending AS (
    SELECT s.user_id, p.price
    FROM sales s
    JOIN membership_enrollments m ON s.user_id = m.user_id
    JOIN product p ON s.product_id = p.product_id
    WHERE s.order_date >= m.enrollment_date 
      AND s.order_date <= m.enrollment_date + INTERVAL '1 year'
)
SELECT user_id, SUM(price * 0.5) as loyalty_points
FROM FirstYearSpending
GROUP BY user_id;
